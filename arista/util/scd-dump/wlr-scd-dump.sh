dumpReg() {
   reg="$1"
   
   # Calculate the full physical address
   addr=$((baseAddr + reg))

   val=$(dd if=/dev/mem bs=4 count=1 skip=$(($addr / 4)) 2>/dev/null | od -An -tx4)

   # Print the formatted result
   printf "0x%04x: %s\n" "$reg" "$val"
}

for fpgaNum in 0 1 2 3; do
   pciAddr="$((fpgaNum+1)):00.0"
   baseAddr=0x$(lspci -vs $pciAddr|grep Memory|head -n1|awk '{print $3}')

   echo "DUMP OF BLACKCOMB FPGA $fpgaNum ($pciAddr):"
   echo "======================================"
   for reg in $regsToDump; do
      dumpReg $reg
   done
done
